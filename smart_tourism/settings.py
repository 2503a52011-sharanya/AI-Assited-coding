# Database Setup
# Primary: MySQL with PyMySQL driver
# Safe auto-detection: If MySQL is not running or db not reachable, use SQLite
DB_ENGINE = os.getenv('DB_ENGINE', 'sqlite').lower()
DB_NAME = os.getenv('DB_NAME', 'ai_smart_tourism')
DB_USER = os.getenv('DB_USER', 'root')
DB_PASSWORD = os.getenv('DB_PASSWORD', '')
DB_HOST = os.getenv('DB_HOST', '127.0.0.1')
DB_PORT = os.getenv('DB_PORT', '3306')

if DB_ENGINE == 'mysql':
    can_connect_mysql = True
    # In local development only, check if localhost MySQL server is accessible
    if DEBUG and not os.getenv('VERCEL') and DB_HOST in ('127.0.0.1', 'localhost'):
        try:
            import pymysql
            conn = pymysql.connect(
                host=DB_HOST,
                user=DB_USER,
                password=DB_PASSWORD,
                port=int(DB_PORT),
                connect_timeout=1
            )
            conn.close()
            can_connect_mysql = True
        except Exception:
            can_connect_mysql = False

    if can_connect_mysql:
        DATABASES = {
            'default': {
                'ENGINE': 'django.db.backends.mysql',
                'NAME': DB_NAME,
                'USER': DB_USER,
                'PASSWORD': DB_PASSWORD,
                'HOST': DB_HOST,
                'PORT': DB_PORT,
                'OPTIONS': {
                    'charset': 'utf8mb4',
                    'init_command': "SET sql_mode='STRICT_TRANS_TABLES'",
                }
            }
        }
    else:
        DATABASES = {
            'default': {
                'ENGINE': 'django.db.backends.sqlite3',
                'NAME': BASE_DIR / 'db.sqlite3',
            }
        }
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }

